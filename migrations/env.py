"""Alembic environment.

Revisions ``v01``–``v11`` run the original Flyway SQL files (``migrations/sql``). New revisions can be
autogenerated from the SQLAlchemy models: ``alembic revision --autogenerate -m "..."``.
"""

from alembic import context
from sqlalchemy import create_engine, pool

from src.adapters.repositories.orm import metadata
from src.infrastructure.config.settings import get_settings

config = context.config


def run_migrations_offline() -> None:
    context.configure(
        url=get_settings().database_url, target_metadata=metadata, literal_binds=True, compare_type=True
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    engine = create_engine(get_settings().database_url, poolclass=pool.NullPool)
    with engine.connect() as connection:
        context.configure(
            connection=connection,
            target_metadata=metadata,
            compare_type=True,
            transaction_per_migration=True,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
